// Copies the color themes and skin/theme metadata from a local whenterminal checkout into whenpc.
//
//   node scripts/import-whenterminal-themes.mjs [path-to-whenterminal]   (default: ../whenterminal)
//
// Writes:
//   src/renderer/themes.css  — :root[data-theme='…'] color-token blocks, verbatim
//   src/themes.json          — skins and themes metadata (id, name, note, swatch colors, dark)
// Skin *shapes* are not copied: whenterminal's skin CSS targets its own markup, so whenpc
// re-implements each skin for the widget in src/renderer/skins.css.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const wt = path.resolve(process.argv[2] || path.join(root, '..', 'whenterminal'));
const src = (p) => fs.readFileSync(path.join(wt, p), 'utf8');

// ---- metadata from src/shared/keymap.ts ----
const keymap = src('src/shared/keymap.ts');
const arrayLiteral = (name) => {
  const m = keymap.match(new RegExp(`export const ${name}[^=]*=\\s*(\\[[\\s\\S]*?\\n\\])`));
  if (!m) throw new Error(`${name} not found in keymap.ts`);
  return Function(`"use strict"; return ${m[1]}`)();
};
const skins = arrayLiteral('SKINS');
const themes = arrayLiteral('THEMES');

// ---- color tokens ----
const styles = src('src/renderer/src/styles.css');
const skinFiles = fs.readdirSync(path.join(wt, 'src/renderer/src/skins')).filter((f) => f.endsWith('.css')).sort();

// poster has no data-theme block: its colors are the leading tokens of :root in styles.css.
const rootBlock = styles.match(/\n:root \{([\s\S]*?)\n\}/)[1];
const COLOR_TOKEN = /^--(paper|ink|signal|signal-ink|on-signal|wash|wash-2|gray|gray-2|gray-3|sel-bg|sel-fg|code-bg|code-fg|line|shadow|syn-[a-z]+|diff-[a-z-]+)$/;
const posterDecls = [];
for (const decl of rootBlock.replace(/\/\*[\s\S]*?\*\//g, '').split(';')) {
  const m = decl.trim().match(/^(--[\w-]+)\s*:\s*([\s\S]+)$/);
  if (m && COLOR_TOKEN.test(m[1])) posterDecls.push(`  ${m[1]}: ${m[2].trim()};`);
}

// As in whenterminal, poster's tokens are also the base every other theme inherits (some themes
// only override part of them, e.g. paper has no --sel-bg).
const blocks = [`/* poster — whenterminal styles.css :root; base for all themes */\n:root, :root[data-theme='poster'] {\n${posterDecls.join('\n')}\n  color-scheme: light;\n}`];
const blockRe = /^:root\[data-theme='([\w-]+)'\] \{\n([\s\S]*?)^\}/gm;
const collect = (css, file) => {
  for (const m of css.matchAll(blockRe)) blocks.push(`/* ${m[1]} — ${file} */\n:root[data-theme='${m[1]}'] {\n${m[2]}}`);
};
collect(styles, 'styles.css');
for (const f of skinFiles) collect(src(`src/renderer/src/skins/${f}`), `skins/${f}`);

const found = new Set(blocks.map((b) => b.match(/data-theme='([\w-]+)'/)[1]));
const missing = themes.filter((t) => !found.has(t.id)).map((t) => t.id);
if (missing.length) throw new Error(`no CSS block for themes: ${missing.join(', ')}`);

const header = `/* GENERATED by scripts/import-whenterminal-themes.mjs from whenterminal — do not edit by hand. */\n\n`;
fs.writeFileSync(path.join(root, 'src/renderer/themes.css'), header + blocks.join('\n\n') + '\n');
fs.writeFileSync(path.join(root, 'src/themes.json'), JSON.stringify({ skins, themes }, null, 2) + '\n');
console.log(`imported ${skins.length} skins, ${themes.length} themes (${blocks.length} CSS blocks) from ${wt}`);
